import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { Resvg } from '@resvg/resvg-js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = process.argv[2] ?? 'Z:/Projects/Dispatch AI/ui/public/logo200/index.html';
const html = await readFile(sourcePath, 'utf8');
const figures = [...html.matchAll(/<figure>([\s\S]*?)<\/figure>/g)];
const output = path.join(root, 'assets', 'agent-avatars');
await mkdir(output, { recursive: true });
const entries = [];
for (const figure of figures) {
  const body = figure[1];
  const number = Number(body.match(/<figcaption><b>(\d+)<\/b>/)?.[1]);
  const svg = body.match(/<div class="art"><svg\b[\s\S]*?<\/svg>/)?.[0]?.replace(/^<div class="art">/, '');
  if (!number || !svg) continue;
  const png = new Resvg(svg, { fitTo: { mode: 'width', value: 128 } }).render().asPng();
  const file = `mark-${String(number).padStart(3, '0')}.png`;
  await writeFile(path.join(output, file), png);
  entries.push(`  ${number}: require('../assets/agent-avatars/${file}'),`);
}
if (entries.length < 100) throw new Error(`Expected the 200-mark gallery; extracted only ${entries.length} images.`);
const map = `// Generated by scripts/build-agent-avatars.mjs from the user's Dispatch logo pack.\nexport const agentAvatarImages: Record<number, number> = {\n${entries.join('\n')}\n};\nexport const agentAvatarIds = Object.keys(agentAvatarImages).map(Number);\n`;
await writeFile(path.join(root, 'src', 'agentAvatars.ts'), map);
console.log(`Built ${entries.length} native agent avatar assets.`);
